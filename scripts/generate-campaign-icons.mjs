import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

import dynamicIconImports from "../node_modules/lucide-react/dynamicIconImports.mjs";

const projectRoot = process.cwd();
const lucidePackageRoot = path.join(projectRoot, "node_modules", "lucide-react");
const lucidePackage = JSON.parse(
  await readFile(path.join(lucidePackageRoot, "package.json"), "utf8"),
);
const iconVersion = String(lucidePackage.version);
const iconNames = Object.keys(dynamicIconImports).sort();
const generatedSourceDirectory = path.join(projectRoot, "src", "generated");
const generatedAssetDirectory = path.join(
  projectRoot,
  "public",
  "generated",
  "lucide",
  `v${iconVersion}`,
);
const allowedTags = new Set([
  "circle",
  "ellipse",
  "line",
  "path",
  "polygon",
  "polyline",
  "rect",
]);
const allowedAttributes = new Set([
  "cx",
  "cy",
  "d",
  "fill",
  "height",
  "points",
  "r",
  "rx",
  "ry",
  "width",
  "x",
  "x1",
  "x2",
  "y",
  "y1",
  "y2",
]);

function escapeXml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll('"', "&quot;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;");
}

function createSvg(iconName, iconNode) {
  const children = iconNode.map(([tag, attributes]) => {
    if (!allowedTags.has(tag)) {
      throw new Error(`Unsupported Lucide tag "${tag}" in ${iconName}.`);
    }

    const serializedAttributes = Object.entries(attributes)
      .filter(([name]) => name !== "key")
      .map(([name, value]) => {
        if (!allowedAttributes.has(name)) {
          throw new Error(
            `Unsupported Lucide attribute "${name}" in ${iconName}.`,
          );
        }

        return `${name}="${escapeXml(value)}"`;
      })
      .join(" ");

    return `<${tag}${serializedAttributes ? ` ${serializedAttributes}` : ""}/>`;
  });

  return [
    '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="#000" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">',
    ...children,
    "</svg>",
    "",
  ].join("\n");
}

async function writeIfChanged(filePath, contents) {
  let currentContents = null;

  try {
    currentContents = await readFile(filePath, "utf8");
  } catch {
    // The generated file does not exist yet.
  }

  if (currentContents !== contents) {
    await writeFile(filePath, contents, "utf8");
  }
}

await mkdir(generatedSourceDirectory, { recursive: true });
await mkdir(generatedAssetDirectory, { recursive: true });

const generatedNotice =
  "// Generated by scripts/generate-campaign-icons.mjs. Do not edit manually.\n";
await writeIfChanged(
  path.join(generatedSourceDirectory, "lucide-campaign-icon-version.ts"),
  `${generatedNotice}export const lucideCampaignIconVersion = ${JSON.stringify(iconVersion)};\n`,
);
await writeIfChanged(
  path.join(generatedSourceDirectory, "lucide-campaign-icon-names.ts"),
  `${generatedNotice}export const lucideCampaignIconNames = ${JSON.stringify(iconNames, null, 2)} as const;\n\nexport type LucideCampaignIconName = (typeof lucideCampaignIconNames)[number];\n`,
);

const existingSvgCount = (await readdir(generatedAssetDirectory)).filter(
  (fileName) => fileName.endsWith(".svg"),
).length;

if (existingSvgCount !== iconNames.length) {
  for (const iconName of iconNames) {
    if (!/^[a-z0-9-]+$/.test(iconName)) {
      throw new Error(`Unsafe Lucide icon name: ${iconName}.`);
    }

    const iconModule = await dynamicIconImports[iconName]();
    const iconNode = iconModule.__iconNode;

    if (!Array.isArray(iconNode)) {
      throw new Error(`Lucide icon data is unavailable for ${iconName}.`);
    }

    await writeIfChanged(
      path.join(generatedAssetDirectory, `${iconName}.svg`),
      createSvg(iconName, iconNode),
    );
  }
}

await writeIfChanged(
  path.join(generatedAssetDirectory, "LICENSE.txt"),
  await readFile(path.join(lucidePackageRoot, "LICENSE"), "utf8"),
);
await writeIfChanged(
  path.join(generatedAssetDirectory, "manifest.json"),
  `${JSON.stringify({ count: iconNames.length, version: iconVersion }, null, 2)}\n`,
);

console.log(
  `Campaign icon assets ready: ${iconNames.length} Lucide icons (v${iconVersion}).`,
);
